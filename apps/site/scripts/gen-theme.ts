// Generates the site's theme CSS from a WhileUI preset. Imports nothing from
// React, React Native or Uniwind — the token layer is renderer-free.
// Does not use `themePresetToCss()`: that emits Uniwind's `@variant light/dark`,
// and plain Tailwind 4 has no `light` variant, so this emits `:root` + `.dark`.
// Run: `bun run gen:theme`

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  WHILEUI_PRESET_SOFT,
  themePresetToCssVariables,
  type ThemePreset,
} from '../../../packages/ui/src/lib/theme-presets';

const PRESET: ThemePreset = WHILEUI_PRESET_SOFT;

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/theme.generated.css');

// Only `--color-*` belongs in `@theme`; `--app-color-*` is the JS-side mirror.
function partition(vars: Record<string, string>) {
  const theme: Record<string, string> = {};
  const app: Record<string, string> = {};
  for (const [name, value] of Object.entries(vars)) {
    (name.startsWith('--app-') ? app : theme)[name] = value;
  }
  return { theme, app };
}

const render = (vars: Record<string, string>, indent: string) =>
  Object.entries(vars)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join('\n');

const { light, dark, visual } = themePresetToCssVariables(PRESET);
const lightSplit = partition(light);
const darkSplit = partition(dark);

const css = `/* GENERATED by scripts/gen-theme.ts — do not edit.
   Preset: ${PRESET.name} — ${PRESET.description}
   Regenerate with: bun run gen:theme */

@theme {
  /* Visual tokens are unitless; the DOM uses calc(var(--x) * 1px). */
${render(visual, '  ')}

${render(lightSplit.theme, '  ')}
}

@layer base {
  :root {
${render(lightSplit.app, '    ')}
  }

  .dark {
${render(darkSplit.theme, '    ')}
${render(darkSplit.app, '    ')}
  }
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, css, 'utf8');

const count = Object.keys(visual).length + Object.keys(light).length;
console.log(`theme.generated.css written — preset "${PRESET.name}", ${count} variables`);
